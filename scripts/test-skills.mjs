import assert from 'node:assert/strict';
import { SKILL_CATALOG, SKILL_PROFILES, MAX_SELECTED_SKILLS, MAX_STAGE_SKILL_CHARS, parseSkillMarkdown, normalizeSkill, buildStageSkillContext, getProfileSkillIds } from '../src/skill-library.js';
assert.equal(SKILL_CATALOG.length, 38, 'starter pack must contain 15 Superpowers, 22 Caveman and one guideline');
assert.equal(SKILL_CATALOG.filter(s=>s.group==='Superpowers').length,15);
assert.equal(SKILL_CATALOG.filter(s=>s.group==='Caveman').length,22);
assert.equal(getProfileSkillIds('balanced').length,MAX_SELECTED_SKILLS);
assert.ok(Object.keys(SKILL_PROFILES).includes('karpathy'));
const parsed=parseSkillMarkdown('---\nname: My Skill\ndescription: A test skill\nstage: code\n---\n# My Skill\nUse small, verifiable changes.','SKILL.md');
assert.equal(parsed.name,'My Skill'); assert.equal(parsed.stage,'code'); assert.match(parsed.content,/verifiable/);
assert.throws(()=>parseSkillMarkdown('   '),/boş/i);
assert.throws(()=>parseSkillMarkdown('x'.repeat(50001)),/50 KB/i);
assert.equal(normalizeSkill({name:'bad',content:'x'.repeat(12001)}),null);
const many=Array.from({length:12},(_,i)=>({id:'x'+i,name:'Skill '+i,stage:'all',content:'A'.repeat(1000)}));
const context=buildStageSkillContext(many,'code');
assert.ok(context.includedIds.length<=MAX_SELECTED_SKILLS);
assert.ok(context.charCount<=MAX_STAGE_SKILL_CHARS);
assert.ok(context.promptText.includes('AI STUDIO SKILLS'));
const planOnly=buildStageSkillContext([{id:'p',name:'Plan',stage:'plan',content:'Plan carefully.'}],'review');
assert.equal(planOnly.includedIds.length,0);
const cap=buildStageSkillContext([{id:'huge',name:'Huge',stage:'code',content:'Z'.repeat(40000)}],'code');
assert.ok(cap.charCount<=MAX_STAGE_SKILL_CHARS);
console.log('Skill library tests passed.');
